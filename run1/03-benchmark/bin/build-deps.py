#!/usr/bin/env python3
# Builds vault/deps/<slug>.md (Needs / Needed by, two hops, fan-out <= 10) from depends_on:: lines above '## Superseded'; rebuilt from scratch.
"""Usage: build-deps.py [VAULT]   (default: $B/vault)

Edge semantics: 'depends_on:: [[b]] (reason)' on page a means a fails or degrades without b.
Each deps/<slug>.md lists, for that page:
  Needs        direct edges a -> b, then second hop b -> c (directed), each with reason and c's `updated` date
  Needed by    direct reverse edges x -> a, then second hop y -> x
Fan-out is capped at 10 per node at each hop (sorted by slug). Lines below a '## Superseded' heading are ignored.
Every file ends with the line 'N pages have no edges' (N counted over the whole wiki).
"""
import os, re, sys, glob, shutil

B = "/workspace/megamind-fleet/run1/03-benchmark"
vault = sys.argv[1] if len(sys.argv) > 1 else f"{B}/vault"
wiki, out = os.path.join(vault, "wiki"), os.path.join(vault, "deps")
CAP = 10
EDGE = re.compile(r"^depends_on:: \[\[([^\]]+)\]\] \((.+)\)\s*$", re.M)

updated, needs = {}, {}
for p in sorted(glob.glob(f"{wiki}/*.md")):
    slug = os.path.basename(p)[:-3]
    text = open(p).read()
    m = re.search(r"^updated:\s*(\S+)", text, re.M)
    updated[slug] = m.group(1) if m else "?"
    main = re.split(r"^## Superseded\s*$", text, maxsplit=1, flags=re.M)[0]
    needs[slug] = sorted((t, r) for t, r in EDGE.findall(main))

needed_by = {s: [] for s in needs}
for a, edges in needs.items():
    for b, r in edges:
        needed_by.setdefault(b, []).append((a, r))
for b in needed_by: needed_by[b].sort()

no_edges = sorted(s for s in needs if not needs[s] and not needed_by.get(s))
footer = f"{len(no_edges)} pages have no edges"

def line(src, dst, reason, date_of):
    return f"- {src} -> [[{dst}]] — {reason} (updated {updated.get(date_of, '?')})"

if os.path.isdir(out): shutil.rmtree(out)
os.makedirs(out)
for s in sorted(needs):
    L = [f"# deps: {s}", "", "Generated by bin/build-deps.py from `depends_on::` lines (above `## Superseded`). Edge a -> b: a fails or degrades without b.", ""]
    L.append("## Needs")
    direct = needs[s][:CAP]
    L.append("### Direct")
    L += [line(s, t, r, t) for t, r in direct] or ["- (none)"]
    L.append("### Second hop")
    hop2 = [line(t, t2, r2, t2) for t, _ in direct for t2, r2 in needs.get(t, [])[:CAP]]
    L += hop2 or ["- (none)"]
    L.append("")
    L.append("## Needed by")
    rdirect = needed_by.get(s, [])[:CAP]
    L.append("### Direct")
    L += [f"- [[{x}]] -> {s} — {r} (updated {updated.get(x, '?')})" for x, r in rdirect] or ["- (none)"]
    L.append("### Second hop")
    rhop2 = [f"- [[{y}]] -> {x} — {r2} (updated {updated.get(y, '?')})" for x, _ in rdirect for y, r2 in needed_by.get(x, [])[:CAP]]
    L += rhop2 or ["- (none)"]
    L += ["", footer, ""]
    open(os.path.join(out, f"{s}.md"), "w").write("\n".join(L))

n_edges = sum(len(v) for v in needs.values())
print(f"{len(needs)} pages, {n_edges} edges, {footer}; wrote {out}/")
